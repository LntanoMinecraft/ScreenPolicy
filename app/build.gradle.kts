fun resolveVersionCode(): Int = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull() ?: 4

fun resolveVersionName(): String =
  System.getenv("RELEASE_VERSION")
    ?.trim()
    ?.removePrefix("v")
    ?.takeIf { it.isNotEmpty() }
    ?: System.getenv("GITHUB_SHA")
      ?.trim()
      ?.take(7)
      ?.takeIf { it.isNotEmpty() }
      ?.let { "dev-$it" }
    ?: "4.0"
